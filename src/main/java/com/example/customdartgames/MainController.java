package com.example.customdartgames;

import com.example.customdartgames.model.Game;
import com.example.customdartgames.model.ScoreTrackable;
import com.example.customdartgames.model.User;
import com.example.customdartgames.model.UserGameSecondaryStats;
import com.example.customdartgames.model.UserGameStats;
import com.example.customdartgames.model.UserGameStatsId;
import com.example.customdartgames.repository.GameRepository;
import com.example.customdartgames.repository.UserGameStatsRepository;
import com.example.customdartgames.repository.UserGameSecondaryStatsRepository;
import com.example.customdartgames.repository.UserRepository;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import com.example.customdartgames.util.Util;

import org.apache.commons.lang3.StringUtils;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;

/**
 * Web controller for every page and form submission under {@code /dart}: home, rules, the player leaderboard/creation
 * form, and the whole play flow (pick a game, set up players, play, record the result).
 * <p>
 * Each seeded game has a {@code ..._CODE} constant below, in the same order the game rows are seeded in
 * {@code CustomDartGamesApplication}. These constants are the only link between a {@link Game} row's id and its
 * game-specific behavior here (required player count, which template renders it) — they aren't otherwise tied together,
 * so adding a game means updating both the seeder and this class.
 */
@Controller
@RequestMapping(path = "/dart") // URLs start with .../dart
public class MainController {

	public static final int CRICKET_CODE = 1;
	public static final int CRICKET_HONOR_CODE = 2;
	public static final int FIVE_OH_ONE_CODE = 3;
	public static final int THREE_OH_ONE_CODE = 4;
	public static final int ONE_OH_ONE_CODE = 5;
	public static final int SCRAM_CODE = 6;
	public static final int SCRAM_4P_CODE = 7;
	public static final int SCRAM_3P_CODE = 8;
	public static final int OZONE_CODE = 9;
	public static final int OZONE_3P_CODE = 10;
	public static final int BASEBALL_CODE = 11;
	public static final int BALLBASE_CODE = 12;
	public static final int CLOCK_CODE = 13;
	public static final int FAST_CLOCK_CODE = 14;
	public static final int GEO_JURA_CODE = 15;
	public static final int PURPLE_STAIN_CODE = 16;
	public static final int KILLER_CODE = 17;

	public static final int ZERO_PLAYER = 0;
	public static final int TWO_PLAYERS = 2;
	public static final int THREE_PLAYERS = 3;
	public static final int FOUR_PLAYERS = 4;
	public static final int SIX_PLAYERS = 6;
	public static final int TEN_PLAYERS = 10;

	public static final String VARIANT = "variant";
	public static final String MIN_PLAYERS = "minPlayers";
	public static final String GAMES = "games";
	public static final String REDIRECT_DART_PLAY = "redirect:/dart/play";

	@Autowired // This means to get the bean called userRepository auto-generated by Spring
	private UserRepository userRepository;

	@Autowired
	private GameRepository gameRepository;

	@Autowired
	private UserGameStatsRepository userGameStatsRepository;

	@Autowired
	private UserGameSecondaryStatsRepository userGameSecondaryStatsRepository;

	/**
	 * Home page.
	 *
	 * @return the {@code home} view name
	 */
	@GetMapping(path = "/")
	public String home() {
		return "home";
	}

	/**
	 * Rules page: every seeded game with its description, rendered as an accordion.
	 *
	 * @param model
	 *            receives the full {@code games} list
	 * @return the {@code rules} view name
	 */
	@GetMapping(path = "/rules")
	public String rules(Model model) {
		model.addAttribute(GAMES, gameRepository.findAll());
		return "rules";
	}

	/**
	 * Leaderboard: one row per player, one best/worst score pair per game. Delegates to {@link Util#computeBestScore}
	 * twice — once for the primary {@link UserGameStats} (every game), once for {@link UserGameSecondaryStats}
	 * (currently Scram's attacker "penalties inflicted" count only), since the two are independent tables with their
	 * own best-score direction.
	 *
	 * @param model
	 *            receives {@code games}, {@code users}, and both stat maps (primary and secondary), each as
	 *            {@code statsByUserAndGame*} (per user, per game, the stat row) and {@code bestPerGame*} (per game, the
	 *            best score across everyone) so the view can highlight the current leader per game
	 * @return the {@code players} view name
	 */
	@GetMapping(path = "/players")
	public String players(Model model) { // model is the spring mvc's way to pass data from controller to view.
		List<Game> games = gameRepository.findAll();
		List<User> users = userRepository.findAll();
		List<UserGameStats> stats = userGameStatsRepository.findAllWithUserAndGame();
		List<UserGameSecondaryStats> statsSecondary = userGameSecondaryStatsRepository.findAllWithUserAndGame();

		Map<Integer, Map<Integer, ScoreTrackable>> statsByUserAndGame = new HashMap<>(); // (User id,(Game id,////
																							// UserGameStats)
		Map<Integer, Integer> bestPerGame = new HashMap<>(); // Game id, bestScore

		// Compute stats and the best scores around all players
		Util.computeBestScore(stats, statsByUserAndGame, bestPerGame, false);

		// Compute stats and the best scores SCRAM ONLY (secondary attackers stats)
		Map<Integer, Map<Integer, ScoreTrackable>> statsByUserAndGameSecondary = new HashMap<>();
		Map<Integer, Integer> bestPerGameSecondary = new HashMap<>();
		// Force higher score with a boolean flag true
		Util.computeBestScore(statsSecondary, statsByUserAndGameSecondary, bestPerGameSecondary, true);

		model.addAttribute(GAMES, games);
		model.addAttribute("users", users);
		model.addAttribute("statsByUserAndGame", statsByUserAndGame);
		model.addAttribute("bestPerGame", bestPerGame);
		model.addAttribute("statsByUserAndGameSecondary", statsByUserAndGameSecondary);
		model.addAttribute("bestPerGameSecondary", bestPerGameSecondary);
		return "players";
	}

	/**
	 * Form to add a new player.
	 *
	 * @return the {@code player-form} view name
	 */
	@GetMapping(path = "/players/new")
	public String newPlayerForm() {
		return "player-form";
	}

	/**
	 * Creates a player from the submitted username, unless one with that username already exists (case-sensitive exact
	 * match, after the same trim/capitalize normalization applied to the new one).
	 *
	 * @param username
	 *            raw username as typed in the form; normalized to "Capitalized, trimmed" before saving
	 * @return redirect to {@code /dart/players}
	 */
	@PostMapping(path = "/add")
	public String addPlayer(@RequestParam String username) {

		if (userRepository.findByUsername(username) == null) {
			String formattedUsername = (StringUtils.capitalize(username.toLowerCase())).trim();
			User user = new User();
			user.setUsername(formattedUsername);
			userRepository.save(user);
		}

		return "redirect:/dart/players";
	}

	/**
	 * Game picker: the first step of the play flow.
	 *
	 * @param model
	 *            receives the full {@code games} list
	 * @return the {@code play} view name
	 */
	@GetMapping(path = "/play")
	public String play(Model model) {
		List<Game> games = gameRepository.findAll();

		model.addAttribute(GAMES, games);
		return "play";
	}

	/**
	 * Computes how many players the chosen game needs, then redirects to player selection. Model attributes don't
	 * survive a {@code redirect:} in Spring MVC, so {@code gameId}/{@code playerNumber} are passed as query params
	 * instead and re-declared as {@code @RequestParam} on {@link #playersSetup}.
	 *
	 * @param gameId
	 *            the chosen game's id, one of the {@code ..._CODE} constants
	 * @return redirect to {@code /dart/play/players-setup} with {@code gameId} and the computed {@code playerNumber} as
	 *         query params
	 */
	@PostMapping(path = "/play/start")
	public String playStart(@RequestParam Integer gameId) {

		// Set the playerNumber based on the game code
		Integer playerNumber = switch (gameId) {
		case CRICKET_CODE, CRICKET_HONOR_CODE, PURPLE_STAIN_CODE, KILLER_CODE, OZONE_3P_CODE -> SIX_PLAYERS;
		case FIVE_OH_ONE_CODE, THREE_OH_ONE_CODE, ONE_OH_ONE_CODE, BASEBALL_CODE, BALLBASE_CODE, CLOCK_CODE,
				FAST_CLOCK_CODE, GEO_JURA_CODE ->
			TEN_PLAYERS;
		case SCRAM_CODE, OZONE_CODE -> TWO_PLAYERS;
		case SCRAM_3P_CODE -> THREE_PLAYERS;
		default -> FOUR_PLAYERS;
		};

		// redirect on player set up.
		return "redirect:/dart/play/players-setup?gameId=" + gameId + "&playerNumber=" + playerNumber;
	}

	/**
	 * Player selection page: pick who's playing, in play order. Re-validates {@code playerNumber} against the game's
	 * allowed range/exact count — if it's out of bounds (e.g. someone hand-edited the URL), redirects back to itself
	 * with a corrected value instead of rendering. Some game codes also add {@code minPlayers} and/or
	 * {@code stopperCount} model attributes the view reads to enforce a minimum selection or color-code
	 * stopper/attacker chips (Scram).
	 *
	 * @param gameId
	 *            the chosen game's id, one of the {@code ..._CODE} constants
	 * @param playerNumber
	 *            how many players this game needs, as computed by {@link #playStart}
	 * @param model
	 *            receives {@code game}, {@code users}, and {@code playerNumber} for the picker to render
	 * @return the {@code players-setup} view name, or a {@code redirect:} back to this same endpoint with a corrected
	 *         {@code playerNumber} if the one given was invalid for this game
	 */
	@GetMapping(path = "/play/players-setup")
	public String playersSetup(@RequestParam("gameId") Integer gameId,
			@RequestParam("playerNumber") Integer playerNumber, Model model) {
		List<User> user = userRepository.findAll();
		String redirectionUrl = "redirect:/dart/play/players-setup?gameId=" + gameId + "&playerNumber=";

		// Secured parameters
		switch (gameId) {
		// if playerNumber > 6 or playerNumber < 1
		case CRICKET_CODE, CRICKET_HONOR_CODE, PURPLE_STAIN_CODE, KILLER_CODE -> {
			if (playerNumber > SIX_PLAYERS || playerNumber < ZERO_PLAYER) {
				return redirectionUrl + SIX_PLAYERS; // redirect to 6 players
			}
		}
		case FIVE_OH_ONE_CODE, THREE_OH_ONE_CODE, ONE_OH_ONE_CODE, BASEBALL_CODE, BALLBASE_CODE, CLOCK_CODE,
				FAST_CLOCK_CODE, GEO_JURA_CODE -> {
			if (playerNumber > TEN_PLAYERS || playerNumber < ZERO_PLAYER) {
				return redirectionUrl + TEN_PLAYERS; // redirect to 10 players
			}
		}
		case SCRAM_CODE, OZONE_CODE -> {
			if (playerNumber != TWO_PLAYERS) {
				return redirectionUrl + TWO_PLAYERS; // redirect to 2 players
			}
		}
		case OZONE_3P_CODE -> {
			model.addAttribute(MIN_PLAYERS, 3);
			if (playerNumber > SIX_PLAYERS || playerNumber < ZERO_PLAYER) {
				return redirectionUrl + SIX_PLAYERS; // redirect to 6 players
			}
		}
		case SCRAM_3P_CODE -> {
			model.addAttribute("stopperCount", 1);
			model.addAttribute(MIN_PLAYERS, 3);
			if (playerNumber != THREE_PLAYERS) {
				return redirectionUrl + THREE_PLAYERS; // redirect to 3 players
			}
		}
		case SCRAM_4P_CODE -> {
			model.addAttribute("stopperCount", 2);
			model.addAttribute(MIN_PLAYERS, 4);
			if (playerNumber != FOUR_PLAYERS) {
				return redirectionUrl + FOUR_PLAYERS; // redirect to 4 players
			}
		}
		default -> {
			return REDIRECT_DART_PLAY;
		}
		}

		// Because it's optional, need to be wrapped as an object Game
		gameRepository.findById(gameId).ifPresent(game -> model.addAttribute("game", game));
		model.addAttribute("users", user);
		model.addAttribute("playerNumber", playerNumber);
		return "players-setup";
	}

	/**
	 * Routes to the chosen game's scoring screen, in the order players were selected in. Games with multiple variants
	 * (Cricket, Countdown, Scram, Ozone, Baseball, Clock) share one template and are told apart by the {@code variant}
	 * model attribute the template/JS switch on.
	 *
	 * @param gameId
	 *            the chosen game's id, one of the {@code ..._CODE} constants
	 * @param orderedPlayerIds
	 *            player ids as submitted by the setup form, in play order
	 * @param model
	 *            receives {@code game}, {@code players} (resolved from {@code orderedPlayerIds}, in that order), and
	 *            any game-specific attribute (e.g. {@code variant}, {@code startingScore})
	 * @return the game's view name, or {@code redirect:/dart/play} if {@code gameId} doesn't match any known game
	 */
	@PostMapping(path = "/play/start-game")
	public String startGame(@RequestParam("gameId") Integer gameId,
			@RequestParam("orderedPlayerIds") List<String> orderedPlayerIds, Model model) {

		Game game = gameRepository.findById(gameId).orElseThrow();

		List<User> players = new java.util.ArrayList<>(List.of());

		for (String playerId : orderedPlayerIds) {
			int realPlayerId = Integer.parseInt(playerId.trim());
			userRepository.findById(realPlayerId).ifPresent(players::add); // wrapper because optional
		}

		model.addAttribute("game", game);
		model.addAttribute("players", players);

		final String scram = "game-scram";

		switch (gameId) {
		case CRICKET_CODE -> {
			model.addAttribute(VARIANT, "cricket");
			return "game-cricket";
		}
		case CRICKET_HONOR_CODE -> {
			model.addAttribute(VARIANT, "cricket-honor");
			return "game-cricket";
		}

		case FIVE_OH_ONE_CODE, THREE_OH_ONE_CODE, ONE_OH_ONE_CODE -> {
			int startingScore = switch (gameId) {
			case FIVE_OH_ONE_CODE -> 501;
			case THREE_OH_ONE_CODE -> 301;
			default -> 101;
			};
			model.addAttribute("startingScore", startingScore);
			return "game-countdown";
		}
		case SCRAM_CODE -> {
			model.addAttribute(VARIANT, "scram");
			return scram;
		}
		case SCRAM_4P_CODE -> {
			model.addAttribute(VARIANT, "scram-2v2");
			return scram;
		}
		case SCRAM_3P_CODE -> {
			model.addAttribute(VARIANT, "scram-2v1");
			return scram;
		}
		case OZONE_CODE -> {
			model.addAttribute(VARIANT, "ozone");
			return "game-ozone";
		}
		case OZONE_3P_CODE -> {
			model.addAttribute(VARIANT, "ozone-3p");
			return "game-ozone";
		}
		case BASEBALL_CODE -> {
			model.addAttribute(VARIANT, "baseball");
			return "game-baseball";
		}
		case BALLBASE_CODE -> {
			model.addAttribute(VARIANT, "ballbase");
			return "game-baseball";
		}
		case CLOCK_CODE -> {
			return "game-clock";
		}
		case FAST_CLOCK_CODE -> {
			model.addAttribute(VARIANT, "fast-clock");
			return "game-clock";
		}
		case GEO_JURA_CODE -> {
			return "game-geo-jura";
		}
		case PURPLE_STAIN_CODE -> {
			return "game-purple-stain";
		}
		case KILLER_CODE -> {
			return "game-killer";
		}
		default -> {
			return REDIRECT_DART_PLAY;
		}
		}

	}

	/**
	 * Records a finished game's result for the winning player: creates their {@link UserGameStats} row for this game if
	 * they don't have one yet, otherwise updates best/worst via {@link Util#saveScoresToStats}.
	 * {@code resultSecondary}, when present, does the exact same thing independently against
	 * {@link UserGameSecondaryStats} — currently only Scram sends one, for the attacker's "penalties inflicted" count,
	 * which is always higher-is-better regardless of whether the primary score for this game is turn-based.
	 *
	 * @param gameId
	 *            the game's id, one of the {@code ..._CODE} constants
	 * @param userId
	 *            the winning player's id
	 * @param result
	 *            the primary score to register (turns to win, points scored, etc. — direction handled by
	 *            {@link Game#isScoreBasedOnTurn})
	 * @param resultSecondary
	 *            the secondary score to register, if this game tracks one
	 * @return redirect to {@code /dart/play}
	 */
	@PostMapping(path = "/play/finish")
	public String finishGame(@RequestParam("gameId") Integer gameId, @RequestParam("userId") Integer userId,
			@RequestParam("result") Integer result,
			@RequestParam("resultInflicted") Optional<Integer> resultSecondary) {

		UserGameStatsId userGameStatsId = new UserGameStatsId(userId, gameId); // Register an id with winner info
		Game game = gameRepository.findById(gameId).orElseThrow();
		boolean isBasedOnTurn = game.isScoreBasedOnTurn();

		// If no stat line for this player and this game :
		if (userGameStatsRepository.findById(userGameStatsId).isEmpty()) {
			UserGameStats userGameStats = new UserGameStats();
			userGameStats.setId(userGameStatsId);
			userGameStats.setGame(game);
			userGameStats.setBestScore(result);
			userGameStats.setUser(userRepository.findById(userId).orElseThrow());
			userGameStatsRepository.save(userGameStats);
		} else { // else fetch the current best score and compare the best one / and worst too
			userGameStatsRepository.findById(userGameStatsId).ifPresent(userGameStats -> {
				Util.saveScoresToStats(userGameStats, result, isBasedOnTurn);
				userGameStatsRepository.save(userGameStats);
			});
		}

		// Secondary score (Scram only) — independent of whether the primary
		// stat line above was new or already existed.
		if (resultSecondary.isPresent()) {
			Integer resultInflicted = resultSecondary.get();

			// If no stat line for this player and this game :
			if (userGameSecondaryStatsRepository.findById(userGameStatsId).isEmpty()) {
				UserGameSecondaryStats userGameSecondaryStats = new UserGameSecondaryStats();
				userGameSecondaryStats.setId(userGameStatsId);
				userGameSecondaryStats.setGame(game);
				userGameSecondaryStats.setBestScore(resultInflicted);
				userGameSecondaryStats.setUser(userRepository.findById(userId).orElseThrow());
				userGameSecondaryStatsRepository.save(userGameSecondaryStats);
			} else { // else fetch the current best score and compare the best one / and worst too
				userGameSecondaryStatsRepository.findById(userGameStatsId).ifPresent(userGameSecondaryStats -> {
					// Hardcode false because the secondary score is for scram attacker. Scores higher are relevant
					Util.saveScoresToStats(userGameSecondaryStats, resultInflicted, false);
					userGameSecondaryStatsRepository.save(userGameSecondaryStats);
				});
			}
		}

		return REDIRECT_DART_PLAY;
	}

}
